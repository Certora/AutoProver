# the undocumented report


def test_the_report_lists_exactly_the_items_with_no_prose(family):
    """The corpus can only carry what the crates carry, and this is the ask against them.

    It has to be a list of *items*, not of doc-comment lines: what an agent hits is a specific
    name with nothing behind it, and the person fixing it needs that name.
    """
    from composer.scripts.cvlr_api_docs import undocumented_report

    report = undocumented_report(family)
    for crate in family:
        for item in items_of(crate):
            listed = f"`{item.name}`" in report
            assert listed is (not item.docs), f"{item.name} documented={bool(item.docs)}"


def test_the_report_counts_what_it_lists(family):
    # The counts are the measure of whether the ask is being met, so they cannot drift from the
    # list under them.
    from composer.scripts.cvlr_api_docs import undocumented_report

    report = undocumented_report(family)
    total = sum(len(items_of(c)) for c in family)
    missing = sum(1 for c in family for i in items_of(c) if not i.docs)
    assert f"{missing} of {total} items carry no prose documentation." in report


def test_the_report_carries_the_signature_of_each_missing_item(family):
    # Whoever writes the doc comment needs to see what they are documenting without opening the
    # crate; a bare name would send them looking for it.
    from composer.scripts.cvlr_api_docs import undocumented_report

    report = undocumented_report(family)
    item = _named(items_of(_docs("cvlr-asserts")), "cvlr_assert_le")
    assert item is not None and not item.docs
    assert item.signature.splitlines()[0] in report


# ---------------------------------------------------------------------------------------------
# header paths have to be unique
#
# The manual product keys on the header parts (``parts_unique`` in the importer's schema), and a
# crate exporting a macro and the function it expands into is ordinary CVLR: ``cvlr-log`` does it,
# ``cvlr-spec`` does it four times, and ``cvlr-solana-stake`` exports two functions of one name.
# Before this, those entries shadowed each other and the ingest died at the database with a
# constraint error naming no item at all.


def _item(name: str, kind: str, path: str) -> Item:
    return Item(name=name, kind=kind, crate="cvlr-log", path=path, signature=f"{kind} {name}")


def test_one_name_for_two_items_is_told_apart_by_kind():
    # Which is the distinction in every real case: the macro and the function it expands into.
    leaves = _leaves([
        _item("cvlr_log", "macro", "cvlr_log::cvlr_log"),
        _item("cvlr_log", "function", "cvlr_log::log::cvlr_log"),
    ])
    assert leaves == ["cvlr_log (macro)", "cvlr_log (function)"]


def test_one_name_and_one_kind_fall_back_to_the_defining_path():
    # ``cvlr-solana-stake`` exports `get_minimum_delegation` twice, both functions.
    leaves = _leaves([
        _item("get_minimum_delegation", "function", "cvlr_solana_stake::get_minimum_delegation"),
        _item("get_minimum_delegation", "function", "cvlr_solana_stake::tools::get_minimum_delegation"),
    ])
    assert leaves == [
        "cvlr_solana_stake::get_minimum_delegation",
        "cvlr_solana_stake::tools::get_minimum_delegation",
    ]


def test_a_name_that_is_already_unique_is_left_alone(family):
    """Almost every entry, and the reason the qualifier is not applied uniformly.

    An agent reaches these sections by searching for a bare identifier; putting a parenthesis in
    the middle of every header in the corpus to accommodate seven collisions would make the common
    case read worse to buy nothing.
    """
    for crate in family:
        items = items_of(crate)
        assert _leaves(items) == [i.name for i in items]


def test_no_two_sections_share_a_header_path(family):
    manifest = build_manifest(family, source="test")
    headers = [tuple(s.headers) for s in manifest.manual_sections]
    assert len(set(headers)) == len(headers)


def test_indistinguishable_items_are_refused_rather_than_dropped():
    # Same name, same kind, same path: there is nothing left to key on, and silently keeping one
    # of the two is the outcome nobody could detect.
    with pytest.raises(RustdocUnavailable, match="overwrite each other"):
        _leaves([_item("x", "function", "p::x"), _item("x", "function", "p::x")])


