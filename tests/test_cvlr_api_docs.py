# procedural macros


def test_a_proc_macro_crate_is_not_an_empty_crate():
    """rustdoc addresses a proc macro's export under an id unrelated to the item's own.

    The usual ``paths[item_id]`` lookup therefore found nothing, the walk read that as "associated
    item, handled elsewhere", and ``cvlr-derive`` came out empty — while its surface section
    announced itself as the complete, closed listing of a crate that exports nothing.
    """
    items = items_of(_docs("cvlr-derive"))
    assert {i.name for i in items} == {"Nondet", "CvlrLog"}
    assert all(i.crate == "cvlr-derive" for i in items)
    assert all(i.path.startswith("cvlr_derive::") for i in items)


def test_a_derive_is_written_as_a_derive_and_not_as_a_bang():
    # `#[derive(Nondet)]` against `Nondet!` is the difference between compiling and not, and
    # rustdoc's `index` calls all three flavours of procedural macro the same thing.
    item = _named(items_of(_docs("cvlr-derive")), "Nondet")
    assert item is not None
    assert item.signature == "#[derive(Nondet)]"
    assert item.kind == "proc_derive"
